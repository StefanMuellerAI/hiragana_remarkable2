#!/usr/bin/env python3
"""Generates app/src/kana_data.inc from KanjiVG SVGs (hiragana + katakana)."""
import math, re, sys
from pathlib import Path

H_ROWS = [
    ("a",  "あa いi うu えe おo"),
    ("ka", "かka きki くku けke こko"),
    ("sa", "さsa しshi すsu せse そso"),
    ("ta", "たta ちchi つtsu てte とto"),
    ("na", "なna にni ぬnu ねne のno"),
    ("ha", "はha ひhi ふfu へhe ほho"),
    ("ma", "まma みmi むmu めme もmo"),
    ("ya", "やya ゆyu よyo"),
    ("ra", "らra りri るru れre ろro"),
    ("wa", "わwa をwo んn"),
    ("ga", "がga ぎgi ぐgu げge ごgo"),
    ("za", "ざza じji ずzu ぜze ぞzo"),
    ("da", "だda ぢdi づdu でde どdo"),
    ("ba", "ばba びbi ぶbu べbe ぼbo"),
    ("pa", "ぱpa ぴpi ぷpu ぺpe ぽpo"),
    ("klein", "ゃya ゅyu ょyo っtsu"),
]
K_ROWS = [
    ("a",  "アa イi ウu エe オo"),
    ("ka", "カka キki クku ケke コko"),
    ("sa", "サsa シshi スsu セse ソso"),
    ("ta", "タta チchi ツtsu テte トto"),
    ("na", "ナna ニni ヌnu ネne ノno"),
    ("ha", "ハha ヒhi フfu ヘhe ホho"),
    ("ma", "マma ミmi ムmu メme モmo"),
    ("ya", "ヤya ユyu ヨyo"),
    ("ra", "ラra リri ルru レre ロro"),
    ("wa", "ワwa ヲwo ンn"),
    ("ga", "ガga ギgi グgu ゲge ゴgo"),
    ("za", "ザza ジji ズzu ゼze ゾzo"),
    ("da", "ダda ヂdi ヅdu デde ドdo"),
    ("ba", "バba ビbi ブbu ベbe ボbo"),
    ("pa", "パpa ピpi プpu ペpe ポpo"),
    ("klein", "ャya ュyu ョyo ッtsu ーー"),
]

TOKEN = re.compile(r"[MmCcSsLlZz]|-?\d*\.?\d+(?:e-?\d+)?")


def bezier(p0, p1, p2, p3, n=24):
    out = []
    for i in range(1, n + 1):
        t = i / n
        u = 1 - t
        out.append((u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
                    u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1]))
    return out


def parse_path(d):
    toks = TOKEN.findall(d)
    i, cmd = 0, None
    cur = (0.0, 0.0)
    last_ctrl = None
    pts = []

    def num():
        nonlocal i
        v = float(toks[i]); i += 1
        return v

    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]; i += 1
        rel = cmd.islower()
        base = cur if rel else (0.0, 0.0)
        C = cmd.upper()
        if C == "M":
            cur = (base[0] + num(), base[1] + num())
            pts.append(cur); last_ctrl = None
            cmd = "l" if rel else "L"
        elif C == "L":
            cur = (base[0] + num(), base[1] + num())
            pts.append(cur); last_ctrl = None
        elif C == "C":
            c1 = (base[0] + num(), base[1] + num())
            c2 = (base[0] + num(), base[1] + num())
            end = (base[0] + num(), base[1] + num())
            pts += bezier(cur, c1, c2, end); last_ctrl = c2; cur = end
        elif C == "S":
            c1 = (2 * cur[0] - last_ctrl[0], 2 * cur[1] - last_ctrl[1]) if last_ctrl else cur
            c2 = (base[0] + num(), base[1] + num())
            end = (base[0] + num(), base[1] + num())
            pts += bezier(cur, c1, c2, end); last_ctrl = c2; cur = end
        elif C == "Z":
            pass
        else:
            raise ValueError(f"unsupported path command {cmd}")
    return pts


def resample(pts, step):
    """Even arc-length spacing; keeps exact start and end point."""
    cum = [0.0]
    for a, b in zip(pts, pts[1:]):
        cum.append(cum[-1] + math.dist(a, b))
    total = cum[-1]
    n = max(2, int(round(total / step)) + 1)
    out, j = [], 0
    for i in range(n):
        target = total * i / (n - 1)
        while j < len(pts) - 2 and cum[j + 1] < target:
            j += 1
        seg = cum[j + 1] - cum[j]
        t = 0.0 if seg == 0 else (target - cum[j]) / seg
        t = min(max(t, 0.0), 1.0)
        out.append((pts[j][0] + t * (pts[j + 1][0] - pts[j][0]),
                    pts[j][1] + t * (pts[j + 1][1] - pts[j][1])))
    return out


def main(kvg_dir, out_file):
    kvg = Path(kvg_dir)
    lines = ["// Generated by tools/gen_kana_data.py from KanjiVG (CC BY-SA 3.0).",
             "// Do not edit by hand.", ""]
    point_rows, stroke_rows, kana_rows, group_rows = [], [], [], []
    npts = nstrokes = 0
    for script, rows in ((0, H_ROWS), (1, K_ROWS)):
        for gname, spec in rows:
            first_kana = len(kana_rows)
            for item in spec.split():
                glyph, romaji = item[0], item[1:]
                if romaji == "ー":
                    romaji = "-"
                svg = (kvg / f"{ord(glyph):05x}.svg").read_text(encoding="utf-8")
                paths = re.findall(r'<path id="kvg:[0-9a-f]+-s(\d+)"[^>]*\sd="([^"]+)"', svg)
                paths.sort(key=lambda p: int(p[0]))
                labels = [tuple(map(float, m)) for m in
                          re.findall(r'matrix\(1 0 0 1 ([\d.]+) ([\d.]+)\)', svg)]
                first_stroke = nstrokes
                for k, (_, d) in enumerate(paths):
                    pts = resample(parse_path(d), 2.0)
                    lx, ly = labels[k] if k < len(labels) else pts[0]
                    stroke_rows.append(f"  {{{npts}, {len(pts)}, {lx:.1f}f, {ly:.1f}f}},")
                    point_rows.append("  " + " ".join(f"{{{x:.2f}f,{y:.2f}f}}," for x, y in pts))
                    npts += len(pts); nstrokes += 1
                kana_rows.append(
                    f'  {{"{glyph}", "{romaji}", {script}, {len(group_rows)}, {first_stroke}, {len(paths)}}},')
            group_rows.append(f'  {{"{gname}", {script}, {first_kana}, {len(kana_rows) - first_kana}}},')

    lines.append("static const KanaPoint kKanaPoints[] = {")
    lines += point_rows
    lines += ["};", "", "static const KanaStrokeDef kKanaStrokes[] = {"]
    lines += stroke_rows
    lines += ["};", "", "static const KanaDef kKanaDefs[] = {"]
    lines += kana_rows
    lines += ["};", "", "static const KanaGroupDef kKanaGroups[] = {"]
    lines += group_rows
    lines += ["};", ""]
    Path(out_file).write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(kana_rows)} kana, {nstrokes} strokes, {npts} points, {len(group_rows)} groups")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
