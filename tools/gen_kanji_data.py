#!/usr/bin/env python3
"""Generates app/src/kanji_data.inc from KanjiVG SVGs for the kanji listed in
tools/kanji_n5.tsv (character, German meaning, readings).

Usage: gen_kanji_data.py <kanjivg>/kanji app/src/kanji_data.inc

Uses the same path parsing and resampling as gen_kana_data.py, but writes a
separate file so the kana tables stay untouched.
"""
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
from gen_kana_data import parse_path, resample  # noqa: E402

LIST = TOOLS / "kanji_n5.tsv"
PATH_RE = re.compile(r'<path id="kvg:[0-9a-f]+-s(\d+)"[^>]*\sd="([^"]+)"')
LABEL_RE = re.compile(r'matrix\(1 0 0 1 (-?[\d.]+) (-?[\d.]+)\)')


def load_list(path=LIST):
    """[(glyph, meaning, readings)] in file order."""
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        glyph, meaning, readings = line.split("\t")
        out.append((glyph, meaning, readings))
    return out


def c_str(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main(kvg_dir, out_file):
    kvg = Path(kvg_dir)
    point_rows, stroke_rows, kanji_rows = [], [], []
    npts = nstrokes = 0
    for glyph, meaning, readings in load_list():
        svg = (kvg / f"{ord(glyph):05x}.svg").read_text(encoding="utf-8")
        paths = sorted(PATH_RE.findall(svg), key=lambda p: int(p[0]))
        labels = [tuple(map(float, m)) for m in LABEL_RE.findall(svg)]
        if not paths:
            raise SystemExit(f"{glyph}: no strokes in the SVG")
        if len(labels) != len(paths):
            print(f"warning: {glyph}: {len(paths)} strokes but {len(labels)} stroke numbers")
        first = nstrokes
        for k, (_, d) in enumerate(paths):
            pts = resample(parse_path(d), 2.0)
            lx, ly = labels[k] if k < len(labels) else pts[0]
            stroke_rows.append(f"  {{{npts}, {len(pts)}, {lx:.1f}f, {ly:.1f}f}},")
            point_rows.append("  " + " ".join(f"{{{x:.2f}f,{y:.2f}f}}," for x, y in pts))
            npts += len(pts)
            nstrokes += 1
        kanji_rows.append(
            f'  {{"{glyph}", "{c_str(meaning)}", "{c_str(readings)}", {first}, {len(paths)}}},')

    lines = ["// Generated by tools/gen_kanji_data.py from KanjiVG (CC BY-SA 3.0)",
             "// and tools/kanji_n5.tsv. Do not edit by hand.", "",
             "static const KanaPoint kKanjiPoints[] = {"]
    lines += point_rows
    lines += ["};", "", "static const KanaStrokeDef kKanjiStrokes[] = {"]
    lines += stroke_rows
    lines += ["};", "", "static const KanjiDef kKanjiDefs[] = {"]
    lines += kanji_rows
    lines += ["};", ""]
    Path(out_file).write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(kanji_rows)} kanji, {nstrokes} strokes, {npts} points")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
